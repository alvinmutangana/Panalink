export async function getLang(): Promise<Lang> {
  const v = (await cookies()).get("lang")?.value;
  return LANGS.includes(v as Lang) ? (v as Lang) : "en";
}

export async function getDict(): Promise<Dict> {
  return dict[await getLang()];
}
